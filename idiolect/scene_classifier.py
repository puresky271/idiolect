"""生产场景分类器：`user_text` → 场景 key（26 场景体系）。

**为什么需要它**：此前的「每场景长度目标」只存在于探针工具
（`tools/probe/prompt_patch.py`）里，装配器对所有轮次都用同一个全局基线——
于是「附和/同感」和「打工接客」拿到同一个上限，而原作里两者差 2~3 倍。

**设计约束**
  · **高精度优先**：宁可返回 ""（走全局默认）也不误判。误判会把别的场景的长度带进来，
    比不分类更糟。所以规则都是「有明确证据才判」，不做模糊打分。
  · **顺序敏感**：强信号场景（crisis / affection / comfort）先判，泛场景（banter / third_party）最后。
  · 角色专属场景要求 `char` 命中才判——同一个词对不同角色意义不同
    （「练习」对立希是本职，对其他人只是普通话题）。
  · key 与发布数据 `data/scene_stats.json` 的 26 场景定义对齐。

用法：
    from idiolect.scene_classifier import classify
    classify("你今天又想去哪找猫", "乐奈")   # -> "rana_cat"
    classify("今天午饭吃什么", "立希")       # -> ""（无明确场景）
"""
from __future__ import annotations

import re

_RULES: list[tuple[str, str, re.Pattern]] = []


def _rule(scene: str, pattern: str, char: str = "") -> None:
    _RULES.append((scene, char, re.compile(pattern, re.IGNORECASE)))


# ── 1. 强信号情感场景（先判）────────────────────────────────
_rule("crisis", r"(不在了|要消失|会消失|活不下去|不想活|没有我(?:的话)?|不存在了|"
                r"死掉|去死|自杀|离开这个世界|别管我了|你就当我)"
      + r"|如果哪天我(?:不在|没了)")
_rule("affection", r"(我喜欢你|我爱你|爱你|最喜欢你|离不开你|不能没有你|"
                   r"想你(?!帮|做|看|说|听|来|去|给|问)|好想你|想见你|"
                   r"你对我(?:来说)?(?:很|最)重要|对我(?:来说)?(?:很|最)重要|"
                   r"抱抱|想抱抱|抱一下|亲亲|表白|爱死你)")
_rule("comfort", r"(在哭|哭了|想哭|崩溃|撑不住|受不了了|好痛苦|喘不过气|"
                 r"难受死|快疯|害怕得|很害怕)")
_rule("low_mood", r"(最近(?:过得)?不好|好累|很累|太累|累死|压力(?:大|好大|很大)|"
                  r"没精神|提不起(?:劲|精神)|郁闷|好烦|心情不好|不开心|"
                  r"睡不着|状态不好)")
_rule("wellwish", r"(希望(?:你们|你|大家|他|她)|只要(?:你们|你|大家)(?:开心|好)|"
                  r"我(?:怎么样|怎么)都(?:行|可以|无所谓)|我不重要|我无所谓|"
                  r"你们好就行)")

# ── 2. 语言元提问 ──────────────────────────────────────────
_rule("meta_language", r"(你刚才(?:那句|说的|那句话)|什么意思|我没听懂|没听懂|"
                       r"你说的那句|那句话是什?么|你在说什么|那句话什么意思)")

# ── 3. 角色专属（要求 char 命中）────────────────────────────
# 放在 `probe_stance` **之前**：话题比态度更具体。
# （「你是不是还放不下CRYCHIC」对素世是**旧事**场景，不是关系试探）
_rule("rana_guitar", r"(吉他|弦|弹|演出|演奏|曲)", "乐奈")
_rule("rana_food", r"(抹茶|芭菲|冰淇淋|点心|荞麦面|甜)", "乐奈")
_rule("rana_cat", r"(猫|雨)", "乐奈")

_rule("soyo_tea", r"(茶|咖啡|伯爵|泡)", "素世")
_rule("soyo_past", r"(CRYCHIC|春日影|记得|以前|过去|那时候|睦)", "素世")

_rule("anon_beauty", r"(化妆|美妆|护肤|口红|眼影|腮红|底妆|防晒|穿搭|裙子|衣服|发型)", "爱音")
_rule("anon_sns", r"(发帖|账号|照片|视频|自拍|点赞|社交)", "爱音")

_rule("tomori_lyrics", r"(写词|歌词|写不下来|诗)", "灯")
_rule("tomori_nature", r"(昆虫|虫子|西瓜虫|石头|星星|天文|海洋|企鹅|水族馆|独角仙)", "灯")

# 注意：用户侧说「排练」，立希自己说「练习」（她语料里「排练」0 次）——
# 分类器判的是**用户**的话，所以两个词都要收。
_rule("taki_music_pro", r"(编曲|DTM|鼓|练习|排练|作曲|乐理|节拍)", "立希")
_rule("taki_shift", r"(RiNG|接客|打工|凛凛子)", "立希")
_rule("taki_soft_spot", r"(熊猫|Afterglow|afterglow)", "立希")

# ── 4. 关系试探（在角色专属之后）────────────────────────────
_rule("probe_stance", r"(你是不是|是不是那个意思|被你看穿|看穿我|我猜你|你该不会|"
                      r"难道你|你是不是喜欢|你是不是讨厌|你刚才是不是)")

# ── 5. 信息交换 ────────────────────────────────────────────
_rule("schedule", r"(几点|周几|星期几|哪天|明天|后天|昨天|日程|安排|"
                  r"去哪|去那里|什么时候|多久|几号)")
_rule("request", r"(帮我|能不能|可不可以|要不要|你建议|给个建议|怎么办|"
                 r"帮我想|替我|拜托你)")
_rule("fact_qa", r"(是什么|为什么|怎么做|怎么(?:回事|办)|哪个|哪一种|多少|"
                 r"知不知道|什么是|是不是真的)")

# ── 6. 泛场景（最后判）─────────────────────────────────────
_rule("play_along", r"(我也是|我猜也是|对吧|确实|同感|我也这么|我懂|说得对|"
                     r"就是说啊|我也觉得)")
_rule("banter", r"(天气|好热|好冷|下雨|午饭|晚饭|好吃|喝的|哈哈|开玩笑|"
                r"无聊|随便聊|周末|电视剧|综艺)")
_rule("third_party", r"(爱音|立希|素世|爽世|小灯|乐奈|她们|他们|那家伙)")


def classify(user_text: str, char: str = "") -> str:
    """返回场景 key；无明确证据时返回 ""（调用方走全局默认）。

    `char` 为 canonical 中文名（灯/爱音/乐奈/素世/立希）；留空则跳过角色专属规则。
    """
    text = str(user_text or "").strip()
    if not text:
        return ""
    for scene, need_char, rx in _RULES:
        if need_char and need_char != str(char or "").strip():
            continue
        if rx.search(text):
            return scene
    return ""
