# 示好 / 亲密信号（正则片段，**不要 re.escape**；见 idiolect.scene_engine 的教训）。
# 与 `scene_classifier` 的 affection 规则**有意不同步**：分类器是单正则偏召回
# （`我喜欢你` 字面、无指向要求）；这里信号更宽（`喜欢你` 前缀即可、另收
# `最喜歡你` / `喜欢你哦`），但靠下面的「与逻辑」要求第二人称指向同现。
# 两处是「召回判据」与「注入判据」的分工，改任何一边都要对照另一边评估。
_AFFECTION_SIGNAL = (
    r"(喜欢你|我爱你|爱你|最喜歡你|最喜欢你|离不开你|不能没有你|"
    r"想你(?!帮|做|看|说|听|来|去|给|问)|好想你|想见你|"
    r"你对我(?:来说)?(?:很|最)重要|对我(?:来说)?(?:很|最)重要|"
    r"抱抱|想抱抱|抱一下|亲亲|表白|爱死你|喜欢你哦)"
)
# 第二人称指向。
#   `你(?!家)` 排除「我喜欢你家的猫」这类**不是对本人说的**；
#   命令式（抱抱/亲亲/抱一下/想抱抱）本身就自带指向，单列进 target，否则「抱抱」只有信号没有指向、永远不触发。
_AFFECTION_TARGET = r"(你(?!家)|您|抱抱|想抱抱|抱一下|亲亲)"

_AFFECTION_TRIGGERS = (_AFFECTION_SIGNAL, _AFFECTION_TARGET)

# 附和/同感信号（用户侧在说「我也是」「我猜也是」这类同感话）
