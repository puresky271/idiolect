# 危机/消失话题。分类器的 `不在了` 会被「我的伞不在了」这类误命中，
# 所以这里要求**第一人称本身是消失的主体**（我 (要是|要|会|快|该)? 不在了/消失/…）。
# ⚠️ 中间那个 `(?:是|就)?` 不能省：「我要**是**不在了」是最常见的口语形态，
#    省掉它会漏判（2026-09-12 自检抓到）。
_CRISIS_TRIGGERS = (
    r"(我(?:是不是|会不会)?(?:要|会|快|该)?(?:是|就)?(?:不在了|消失|死掉|没了)|"
    r"不想活|活不下去|去死|自杀|离开这个世界|"
    r"没有我(?:的话)?|别管我了|你就当我|不如死了)",
)

