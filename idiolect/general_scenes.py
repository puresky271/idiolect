"""通用场景（13 个，五角色共有）的 turn_logic 模块。

为什么需要这一层：
  角色专属场景（rana_food / soyo_tea / tomori_lyrics …）各自有模块，
  但 **13 个通用场景（crisis / comfort / affection / play_along …）五个人都没有**——
  于是实测最差的那批场景恰好落在这里。`affection` 在两条 probe 臂里都是最差场景：
    立希 中位 2 字（该场景参照中位 12）→ **过度沉默**
    灯   中位 50 字（参照中位 10）      → **过度铺陈**
  同一个场景、两个方向都能错，说明它不是「长度目标」能压住的，需要场景级指引。

参照物（证据只写在这里，**正文里不出现任何统计/语料字样**）：
  · 场景原型来自 `validate_scenes.py:PROTOTYPES["affection"]`
    = 「突然说这个干嘛，我这边还在上课」——本质是**被示好时的挡回**，
      纯 embedding 检索在短句语料上会被长度/风格带偏（灯就抓成了「今天有体育课」），
    所以改用**反应词典锚定**子集（宿主工程的口径，本仓库不带那份词典脚本；
    表里的数字是当时的实测值，按语料重算请用 `tools/distill/scene_char_baseline.py`）：
    角色   锚定 n   中位   p90   均    ｜ L2 检索中位（对照）
    灯       64     10    18   11.0   ｜  12
    爱音    137     19    32   19.7   ｜  16
    素世     46     17    26   17.4   ｜  17
    立希     84     12    30   15.0   ｜  18
    乐奈      3      8     8    8.0   ｜   7
    ⚠️ 乐奈这一格只有 3 条锚定样本，中位数不可当分布用（照仓库口径的
    `data/scene_char_baseline.json` 里同格 n=40）。

    锚定后的中位与 L2 检索同向（灯 10 vs 12、素世 17 vs 17），
    立希从 18 降到 12 —— 但**缺陷方向不变**：她实测只回 2 字。
  · 语料原句（挡回形态，正文的正/反例即取自这些）：
    爱音：「诶？怎么突然说这个」「诶——！？这可是自己的生日啊？」
    素世：「突然怎么了？」「你这是打算夸我？」「呵呵，怎么突然说这个」
    立希：「哈？想跟我吵架？」「……你来干什么？」「……？怎么了？」
    灯　：「诶……？」「诶……努力？」「唔、唔……我觉得、很、可爱……」
    乐奈：「唔……感觉不喜欢」「为什么要用简称啊」

触发用**与逻辑**：示好信号 与 第二人称指向同时命中，避免把第三方语境误触发。
可关闭：`GENERAL_SCENE_TURN_LOGIC_AFFECTION_ENABLED=0`（引擎按 `<PREFIX>_<KEY>_ENABLED` 取）。
"""
from __future__ import annotations

