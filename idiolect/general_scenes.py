# 角色名别名表在 `idiolect/registry.py`（唯一一份），这里只做一次转发。
# 本模块原先自带一张手写表，与 registry 的集合不一致（少 `愛音`/`燈`，
# 多 `らな`/`そよ`），同一个别名在两条路径上会解析成不同结果。
def canon_character(character: str) -> str:
    from .registry import canonicalize_name

    return canonicalize_name(character)


def build_general_scene_blocks(
    character: str,
    user_text: str,
    *,
    session_id: str | None = None,
    max_blocks: int = 1,
    is_developer: bool = False,
) -> list[str]:
    """通用场景 block。无匹配 / 未知角色 / user_text 为空 / 开发者模式 → 空列表。

    `is_developer=True` 时**不触发**——与各角色既有场景子系统一致
    （开发者轮次不该被注入角色场景指引）。

    每个块尾部统一追加 `NO_LITERAL_COPY`：2026-09-12 的真实探针显示，
    正文里的「正例」会被**逐字照抄**（爱音 crisis 5/6、乐奈 crisis 6/6 都等于示例），
    照抄即复读、并把长度拉到示例长度。所以正例一律写成**带槽位的形态示例**，
    这里再补一句约束兜底。
    """
    if is_developer:
        return []
    key = canon_character(character)
    if not key or not user_text:
        return []
    modules = GENERAL_SCENES.get(key)
    if not modules:
        return []
    blocks = build_scene_blocks(user_text, modules, session_id=session_id, max_blocks=max_blocks)
    return [f"{b.rstrip()}\n{NO_LITERAL_COPY}" for b in blocks]
