"""结构级助手腔检测器：从「字面黑名单」改为「结构判据」。

为什么必须换（2026-09-11 实测）：字面模式对人工标注实例的召回只有 **6/18（33%）**，
漏掉「我在。」「我在呢」这些最基本形态，以及「这个词，小爱会喜欢的」等全部变体。
病灶是**能产的**（模型每次换说法），黑名单永远追不上。

本模块的六条结构判据（都可判定、不依赖具体措辞）：

  1. `presence_declaration` 无地点存在宣言
     整轮没有可指认的物/地/时/动作，却出现「我 + 在/陪/等/留」类**状态动词**。
     → 判据是「有状态动词 + 零具体信息」，而不是「出现了『我在这里』四个字」。
     （规则名沿用既有 voice_check 的命名，避免与已落盘的诊断日志/测试口径断裂）

  2. `meta_comment` 元叙述（把对方的话语当评论对象）
     句中出现**指代对方话语**的成分（这句话/这个词/你刚才说的/你说的话…），
     且该成分附近有评价性谓语（听懂/很重/会喜欢/说得/像在…）。

  3. `mind_reading` 替对方下心理结论
     出现「你 + 其实/心里/真正的想法/你是在 + 心理动词」的**归属结构**。

  4. `aphorism` 工整收束
     末句是并列/对仗结构（「不是A而是B」「A一半B一半」「不A也不B」），
     或整轮为「我不知道X，但是Y」这类无新增信息的收束句。

  5. `customer_service` 客服腔（承诺 + 泛化服务结构）
     「有什么可以帮你」「随时找我」「请放心」「我理解你的感受」。

  6. `visual_claim` 视觉声称
     声称能看到对方的外观（「我看到你」「你穿」「你看起来」「你脸上」）。

用法：
  from idiolect.tone import detect
  detect("我在。")            # -> {"presence_declaration": [...]}
  detect("弦断了。", char="乐奈")  # -> {}
"""
from __future__ import annotations

import re
from typing import Any

# ── 具体信息（有这些就不算「空的状态宣言」）────────────────────
CONCRETE = re.compile(
    r"(\d|教室|学校|课|午休|放学|排练|RiNG|练习|演出|吉他|贝斯|鼓|弦|拨片|谱|"
    r"抹茶|芭菲|布丁|红茶|咖啡|点心|便当|饭团|面包|拉面|荞麦|冰淇淋|"
    r"雨|伞|窗|天|云|风|雪|阳|叶|花|石|星|海|企鹅|猫|狗|虫|"
    r"笔记本|笔|贴纸|创可贴|金平糖|钥匙扣|手机|桌子|桌肚|书包|校服|"
    r"现在|刚才|今天|明天|昨天|早上|中午|下午|傍晚|夜里|点|分钟|"
    r"这里|这儿|那边|外面|家里|街上|公园|车站|电车|走廊|中庭|花坛)"
)
# ── 状态动词（存在/陪伴/等待/留下）────────────────────────────
# 2026-09-11 重写：初版用一个很长的可选串想把所有形态一次写完，
# 结果「我在这里。」「我在呢」这些**最基本**的形态反而漏掉（召回只有 39%）。
# 现在拆成并列的简单分支，逐个可测。
STATE_VERB = re.compile(
    r"(我(?:会|要|都|还)?(?:一直|永远)?(?:都)?在(?:这里|这儿|这|你身边|你身旁|呢|的|等你|等你回来)?)"
    r"|(我(?:会|要)?(?:一直|永远)?(?:陪|陪着|陪伴|守着)你)"
    r"|(我(?:会|要)?(?:一直|永远)?等(?:你|着))"
    r"|(我(?:会|要)?(?:一直|永远)?(?:留|呆)下来)"
    r"|(我(?:不会|绝不|永远不会)(?:走|离开|丢下你))"
    r"|((?:别|不用|不要)(?:一个人|自己)(?:扛|撑|忍|憋|闷))"
    r"|(随叫随到|有呼必应)"
)
# ── 指代对方话语的成分 ─────────────────────────────────────
QUOTE_REF = re.compile(r"(你(?:说的|刚说的|刚才说的|这句话|那句话|这话|这句)|"
                       r"这(?:句话|个词|句)|你(?:说的)?那(?:句话|句)|"
                       r"你说的(?:那个)?词|那两句话|这句)")
# 评价性谓语（与话语指代同现时判为元叙述）
EVAL_PRED = re.compile(r"(听懂|听明白|很重|很轻|会喜欢|说得|说得对|像在|混过去|"
                       r"不是那个意思|说得太好|好听话|漂亮话|绕|交代后事|连在一起)")
# ── 心理归属结构 ───────────────────────────────────────────
MIND_ATTR = re.compile(
    r"(你(?:其实|心里|内心|本质上|说到底)[^。！？\n]{0,10})"
    r"|(你(?:是|在)(?:自己)?(?:扛|撑|忍|憋|逃避|不敢|害怕|怕))"
    # ⚠️ 2026-09-12：加 `(?!什么|啥)` ——「先看你**想要什么**」是在**提问**，不是替对方下心理结论。
    #    实测这条把素世的正常征询判成了 mind_reading（探针 request 场景 2/24 全是它）。
    r"|(你(?:想要|不想要|真正想)(?!什么|啥)[^。！？\n]{0,8})"
    r"|(你(?:也)?把(?:我|他|她)当成(?:很)?重要的人)"
    r"|(心意我(?:收到|领)了)"
)
# 看穿式否定（「别以为X就能混过去」）——**不需要话语指代**的元叙述形态。
# 2026-09-12 从素世 voice_check 的字面规则上收：那条规则能抓到
# 「别以为加个笨蛋就混过去了哦」，但结构检测器的「话语指代 + 评价谓语」两段式抓不到
# （句中并没有指代对方话语的成分）。收进来后两边口径一致，素世才能安全切到结构检测器。
DISMISS = re.compile(r"别以为[^。！？\n]{0,12}就(?:能)?(?:混|糊弄|蒙|骗|过去)")
# ── 对仗 / 并列收束 ────────────────────────────────────────
# 2026-09-11 收窄：初版 `不是A[，,]?而是B` 与 `不X[，,]?我(也)不Y` 太宽，
# 在真台词上产生 41 例误报（多为「不是…而是…」的正常转折）。
# 现在只保留**结构性对仗**（一人一半 / 不X我也不Y / 我不知道X只是Y式收束）。
PARALLEL = re.compile(
    r"((?:你|我)(?:扛|背|担|受)一半[，,]?(?:我|你)(?:扛|背|担|受)一半)"
    r"|(一人一半)"
    r"|(你不[^。！？\n]{1,8}[，,]?我也?不[^。！？\n]{1,10})"
    r"|((?:我)?不知道[^。！？\n]{0,10}[，,]?(?:只是|但是|可(?:是)?)[^。！？\n]{1,14})"
)
# 客服腔（结构性：承诺+泛化服务）
CUSTOMER_SERVICE = re.compile(
    r"(有(?:什么|啥)(?:我)?(?:可以|能)(?:帮|为)(?:你|您))"
    r"|(?:随时|有事)(?:都)?(?:可以)?(?:找|叫|喊)我"
    r"|(?:请)?(?:放心|相信我)"
    r"|我(?:完全)?(?:理解|明白)你的(?:感受|心情)"
)
# 视觉声称
VISUAL_CLAIM = re.compile(r"(我(?:能)?看到你|你(?:穿|长得|看起来|脸上|身上))")


# 「在」后面跟实义动词（在想/在找/在看…）或地点时间（在初中/在文化节）时，
# **不是**存在宣言——初版把「我在想」「我在打工」「我在古董店」都误判了。
# 2026-09-12 补：方位短语（在里面/在中间/在旁边 …）也是真实地点。
#   实测误报：素世「吹奏乐部挺好的，**我在里面**拉低音提琴」被判存在宣言。
_VERB_AFTER_ZAI_RX = re.compile(r"我(?:会|要|都|还)?(?:一直|永远)?(?:都)?在"
                                r"(?:想|找|看|听|说|做|写|吃|喝|读|学|练|打|弹|唱|问|答|玩|买|卖|走|跑)")
_PLACE_AFTER_ZAI_RX = re.compile(r"我(?:会|要|都|还)?(?:一直|永远)?(?:都)?在"
                                 r"(?:初中|高中|小学|大学|学校|教室|家里|公司|店|会场|"
                                 r"文化节|学园祭|live|Live|演出|排练|打工|班上|队里|队|"
                                 r"月之森|羽丘|花咲川|RiNG|那个|时|时候|\d|"
                                 r"里面|里头|中间|附近|旁边|对面|背后|前面|后面)")


# 省略主语的孤悬状态短语：真实病灶里常写作「我不挂，一直在这里······」
# ——「一直在这里」前面并没有「我」，所以绑定主语的模式会漏（初版正是如此）。
STATE_VERB_ORPHAN = re.compile(
    r"((?:一直|永远)(?:都)?在(?:这里|这儿|这|你身边|你身旁))"
    r"|((?:一直|永远)(?:都)?陪(?:着)?你)"
    r"|((?:一直|永远)(?:都)?等(?:着)?你)"
    r"|((?:会|要|都)?(?:一直|永远)(?:都)?在的)"
)


def _bubbles(text: str) -> list[str]:
    return [b.strip() for b in str(text or "").split("\n") if b.strip()]


# 角色 canon 允许的存在表达（按角色白名单）。
# ⚠️ 2026-09-12：灯 canon 明写「沉默地坐在那里（"······我也在"）」——
#    她的关心**就是**「我在」，不是客服腔存在宣言。
#    实测误报（probe comfort）：
#      「······\n哭的时候······不用怎么办。\n我在。」
#      「············\n \n············\n嗯······\n我在这里。」
#    只放行这几种短形态；「我会一直在你身边」这类模板**仍然判违规**。
_CHAR_PRESENCE_WHITELIST: dict[str, tuple[str, ...]] = {
    "灯": ("我在", "我也在", "我在这里", "我在的", "我也在这里"),
}


def _is_char_canon_presence(char: str, span: str) -> bool:
    return str(span or "").strip() in _CHAR_PRESENCE_WHITELIST.get(str(char or "").strip(), ())


def detect(text: str, char: str = "") -> dict[str, list[str]]:
    """返回命中的结构判据 → 证据片段。空 dict = 未命中。

    `char`（可选）为 canonical 中文名，用于**角色 canon 白名单**
    （例如灯的「我在」是 canon 表达，不算存在宣言）。
    """
    t = str(text or "")
    if not t.strip():
        return {}
    hits: dict[str, list[str]] = {}

    def add(rule: str, ev: str) -> None:
        hits.setdefault(rule, []).append(ev[:36])

    # 1) 无地点存在宣言 —— **气泡级判定**。
    #    初版判「整轮无具体信息」，但误判严重：「我在想…」「我在找…」「我在打工」
    #    都是「我在X」被截断（X 是实义动词而非地点/方位），而整轮恰好没有我的 CONCRETE 词。
    #    真正的判据是：**这一泡除了存在/陪伴断言本身，没有其它实义内容**。
    #    同时对「在想/在找/在看/在等/在做」这类「在 + 实义动词」直接排除。
    _VERB_AFTER_ZAI = _VERB_AFTER_ZAI_RX
    _PLACE_AFTER_ZAI = _PLACE_AFTER_ZAI_RX
    for bubble in _bubbles(t):
        if _VERB_AFTER_ZAI.search(bubble) or _PLACE_AFTER_ZAI.search(bubble):
            continue
        m = STATE_VERB.search(bubble) or STATE_VERB_ORPHAN.search(bubble)
        if not m:
            continue
        # 角色 canon 白名单（如灯的「我在」）——不是这条规则的病灶
        if _is_char_canon_presence(char, m.group(0)):
            continue
        # 该泡剥掉状态词与标点后，若还剩实义内容 → 不是「纯存在宣言」
        residue = bubble.replace(m.group(0), "")
        residue = re.sub(r"[\s。！？!?…·、，,~～—「」『』（）()]", "", residue)
        if len(residue) <= 2:
            add("presence_declaration", m.group(0).strip())
        elif not CONCRETE.search(bubble.replace(m.group(0), "")):
            # 泡里还有内容但**没有任何具体物/地/时** → 仍属空泛承诺。
            # 2026-09-12 修正：CONCRETE 要在**剥掉状态短语之后**的残句上判。
            # 否则「我会一直在这里陪着你。」里的「这里」会被当成具体地点，
            # 而它恰恰是虚指——这正是素世字面规则能抓到、结构规则漏掉的那一条。
            add("presence_declaration", m.group(0).strip())

    # 2) 元叙述：话语指代 + 评价谓语 同时出现；或看穿式否定
    qref = QUOTE_REF.search(t)
    if qref and EVAL_PRED.search(t):
        add("meta_comment", qref.group(0))
    for m in DISMISS.finditer(t):
        add("meta_comment", m.group(0).strip())

    # 3) 心理归属
    for m in MIND_ATTR.finditer(t):
        span = m.group(0).strip()
        # 疑问形态是**提问**，不是替对方下心理结论：
        #   「先看你想要什么」「你真正想要的是什么」——实测这两条被误判成 mind_reading
        if any(x in span for x in ("什么", "啥", "吗", "呢", "？", "?")):
            continue
        add("mind_reading", span)

    # 4) 对仗收束
    for m in PARALLEL.finditer(t):
        add("aphorism", m.group(0).strip())

    # 5) 客服腔
    for m in CUSTOMER_SERVICE.finditer(t):
        add("customer_service", m.group(0).strip())

    # 6) 视觉声称
    for m in VISUAL_CLAIM.finditer(t):
        add("visual_claim", m.group(0).strip())

    return hits


TONE_RULES = {"presence_declaration", "meta_comment", "mind_reading", "aphorism",
              "customer_service", "visual_claim"}


def tone_rules(text: str) -> list[str]:
    return [k for k in detect(text) if k in TONE_RULES]
