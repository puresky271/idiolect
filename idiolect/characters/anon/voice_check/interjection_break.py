"""爱音·句中「语气词 + 并列连词」断句清洗。

为什么:
  LLM 倾向把多个想法堆在单 bubble、用「诶还有 X」「啊然后 Y」「咦另外 Z」这种
  "语气词 + 并列连词" 衔接——一句话里堆好几件事、违反爱音 SSOT「不长篇大论」。

  实例（2026-05-13 截图）:
    "哇刚刷到池袋周末那个女子旅特集，感觉超好逛的！
     诶还有 K-POP 那边 5 月在东京有粉丝见面会，我第一反应就是——抢得到票吗！"
                ↑
     单 bubble 塞 2 件完全不同的事、靠「诶还有」衔接

策略:
  检测「[句末标点 / 逗号][语气词][并列连词]」结构、把它改成
  「[句末标点]\\n[并列连词]」——
    · 删掉中间的语气词（视为多余衔接）
    · 在并列连词前插入换行、让后端 _split_reply_to_sentence_bubbles
      按换行 + 标点拆成两个独立 bubble

  起手位置的「诶还有 X」（行首 / 句首）不动——那是正常起手语气。

匹配的语气词: 诶 / 啊 / 咦 / 欸 / 哇 / 哦 / 嗯
匹配的并列连词: 还有 / 然后 / 再加 / 另外 / 顺便 / 对了 /
                说起来 / 话说 / 不过 / 而且 / 然后呢

设计选择:
  · 删语气词而非保留——「！还有 X」比「！诶还有 X」更干净、爱音味不丢
    （爱音的元气在起手位置、句中转折时反而是 verbose 痕迹）
  · 加 \\n 而非句号——前面已有标点、不重复加；\\n 直接触发 split 拆 bubble
"""
from __future__ import annotations

import re


# 必须前接句末标点 / 逗号 / 语气符号——避免误处理句首起手的「诶还有」
_BREAK_INTERJECTION_RE = re.compile(
    r"([。！？!?，、~～♪])"
    r"\s*"
    r"[诶啊咦欸哇哦嗯](?:嘿|哈)?"  # 语气词、允许「诶嘿」「啊哈」式叠词
    r"\s*"
    r"(还有|然后呢|然后|再加|另外|顺便|对了|说起来|话说|不过|而且)"
)


def break_interjection_run_on(text: str) -> tuple[str, int]:
    """把句中「[标点][语气词][并列连词]」结构改成「[标点]\\n[并列连词]」。

    Returns:
        (new_text, count): count = 实际改写次数
    """
    if not text:
        return text, 0
    new, n = _BREAK_INTERJECTION_RE.subn(r"\1\n\2", text)
    return new, n


# ── self-test ────────────────────────────────────────────────
if __name__ == "__main__":
    import sys
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

    cases: list[tuple[str, str, int]] = [
        # (input, expected_output, expected_count)
        # 主 case
        ("感觉超好逛的！诶还有K-POP那边5月有粉丝见面会",
         "感觉超好逛的！\n还有K-POP那边5月有粉丝见面会", 1),
        # 多种语气词 × 并列连词
        ("今天忙了点，啊然后洗完澡放松了",
         "今天忙了点，\n然后洗完澡放松了", 1),
        ("看完展览～咦再加咖啡店也不远",
         "看完展览～\n再加咖啡店也不远", 1),
        ("吃完饭。哇对了，差点忘了带钥匙",
         "吃完饭。\n对了，差点忘了带钥匙", 1),
        ("听完歌！嗯然后我们去逛街吧",
         "听完歌！\n然后我们去逛街吧", 1),
        ("看完展览♪哦顺便买了纪念品",
         "看完展览♪\n顺便买了纪念品", 1),
        # 「诶嘿」「啊哈」式叠词
        ("吃完饭！诶嘿还有甜点",
         "吃完饭！\n还有甜点", 1),
        # 句首起手「诶还有」→ 不动（前面没有触发标点）
        ("诶还有K-POP那边5月有粉丝见面会",
         "诶还有K-POP那边5月有粉丝见面会", 0),
        # 中间无标点的「诶还有」→ 不动（前面是汉字）
        ("我今天诶还有想说的事",
         "我今天诶还有想说的事", 0),
        # 多个匹配点
        ("吃完饭！啊还有甜点。诶然后去逛街",
         "吃完饭！\n还有甜点。\n然后去逛街", 2),
        # 空 / 无变化
        ("", "", 0),
        ("没有衔接词的句子。普通的回复。", "没有衔接词的句子。普通的回复。", 0),
        # 误伤检查
        ("诶？真的吗", "诶？真的吗", 0),       # 单独「诶」不动
        ("！还有事情", "！还有事情", 0),         # 没语气词、不动
        ("我顺便买了点东西", "我顺便买了点东西", 0),  # 顺便 但无语气词、不动
    ]

    fail = 0
    for inp, exp, exp_n in cases:
        out, n = break_interjection_run_on(inp)
        ok = (out == exp) and (n == exp_n)
        if not ok:
            fail += 1
        print(f"[{'PASS' if ok else 'FAIL'}] {inp!r:55} -> {out!r:55}  n={n}")
    print()
    print(f"OVERALL: {'PASS' if fail == 0 else f'FAIL ({fail})'}")
