def _enabled() -> bool:
    return os.environ.get("ANON_LONDON_LOGIC_ENABLED", "1").strip() not in ("0", "false", "False", "off", "no", "")


def _detect_trigger(user_text: str) -> Optional[str]:
    """检测留学话题 触发点 keyword、返回命中的 keyword 或 None。"""
    if not user_text:
        return None
    text_lower = user_text.lower()
    # 长 keyword 优先
    flat = sorted(_TRIGGER_KEYWORDS, key=lambda k: -len(k))
    for kw in flat:
        if kw in user_text or kw.lower() in text_lower:
            return kw
    return None


def _is_anon_linked(user_text: str, trigger_kw: str) -> bool:
    """判定 触发点 是否是「在说爱音的事」。

    采用 **negative-signal 优先**策略：
      1. 触发点 紧跟 external-object（伦敦下雨 / 英国电影 / 英国茶 ...）→ 强制 False（偶然提到的）
         即使 ±20 字内有「你」也算地理 / 文化 reference、不是问爱音经历
      2. 否则、默认 True（爱音-linked）——
         95% 提到 留学 / 伦敦 / 英国 都是关于爱音、问句不需要明示「你」
         即使没有 1st/第二人称、问句的默认 target 也是听话人
    """
    if not user_text or not trigger_kw:
        return False
    # 找到 触发点 位置（大小写不敏感）
    text_lower = user_text.lower()
    kw_lower = trigger_kw.lower()
    idx = user_text.find(trigger_kw)
    if idx < 0:
        idx = text_lower.find(kw_lower)
    if idx < 0:
        return False

    # ── Negative signal 1: 触发点 紧跟 external-object（≤5 字后窗口）──
    end_kw = idx + len(trigger_kw)
    after_window = user_text[end_kw:end_kw + 5]
    after_window_lower = after_window.lower()
    for obj_kw in _EXTERNAL_OBJ_KEYWORDS:
        if obj_kw in after_window or obj_kw.lower() in after_window_lower:
            return False

    # ── Default: 爱音-linked ──
    # 不再要求显式 anon-link 词（_ANON_LINK_KEYWORDS 仅作 future fallback、
    # 当前默认信任问句 / topic 的 本能 target 是 listener = 爱音）
    return True


def _classify_意图(user_text: str, anon_linked: bool) -> str:
    """基于 user_text 启发式分类 对方 意图。

    优先级（**安慰 > 调侃 > 深 > 共情 > 试探 > 随口**）：
      为什么 安慰 在 调侃 前？——
        底色 关键 ambiguity："留学失败也没关系" 中「失败」是 调侃 kw、
        但「也没关系」/「加油」是 安慰 kw、wrap 化解 malice。
        安慰 信号词 存在 ⇒ 用户没有 malice、即使 调侃 kw 出现也是 descriptive 用法。
        反之、调侃 kw 存在但无 安慰 wrap ⇒ 真 调侃。

    返回值：
      - "偶然提到的"  ：触发点 命中但和爱音无关
      - "安慰"  ：用户主动安慰（即使共现 共情 / 试探 / 失败 等 word）
      - "调侃"     ：用这件事戏谑或刺激（无 安慰 wrap、单纯扎）
      - "深"        ：信任已高 + 明确深度问（试探 + 深 信号词 + ≥15 字）
      - "共情"    ：用户分享自己 / 朋友的相似经历、想交换共鸣
      - "试探"     ：出于关心或好奇问
      - "随口"      ：随口提到、没有打击 / 深度信号
    """
    if not anon_linked:
        return "偶然提到的"

    text_lower = user_text.lower()

    def _hit(kws: list[str]) -> bool:
        for kw in kws:
            if kw in user_text or kw.lower() in text_lower:
                return True
        return False

    # 优先级 1：安慰（最高、wrap 化解 调侃 kw 的 malice）
    # 底色：「失败」单独出现可能是 调侃、但和 「不容易 / 加油 / 没关系」共现就是 安慰
    if _hit(_MOTIVE_COMFORTING):
        return "安慰"

    # 优先级 2：调侃（无 安慰 wrap、纯戏谑）
    if _hit(_MOTIVE_TEASING):
        return "调侃"

    # 优先级 3：深（试探 词 AND 深 信号词 AND 文本 ≥ 15 字、防短问候误判）
    has_probe = _hit(_MOTIVE_PROBING)
    has_deep = _hit(_MOTIVE_DEEP_MARKERS)
    if has_probe and has_deep and len(user_text) >= 15:
        return "深"

    # 优先级 4：共情（用户分享自己经历）
    if _hit(_MOTIVE_EMPATHIC):
        return "共情"

    # 优先级 5：试探（普通好奇问）
    if has_probe:
        return "试探"

    # 兜底：触发点 + anon-link 但没有任何 意图 词、当 随口
    return "随口"


