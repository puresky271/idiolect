def _render_full_defense(user_text: str, trigger_kw: str, 意图: str, *, is_developer: bool) -> str:
    """渲染防御外壳完整 prompt——按 dev / guest 关系基调分流。

    **关系分流哲学（用户拍板 2026-05-10）**：
      系统主 prompt 已经告诉爱音「对方是青空（朋友）」 or「对方是访客（陌生人）」、
      她**知道**自己面对的是谁——这是 in-底色 关系态、不是元模式。
      本模块的 prompt 在两种关系下：
        · 同一个 意图 下、姿态 的具体行为不同（朋友前可松、陌生人前必紧）
        · 底色 arc / reflection / 风格提示等 base 内容一致（爱音的内核不变）
        · cognitive header 的「关系基调」slot 注入相应描述
    """
    head = "（话题：留学 / 伦敦 / 英国 话题——**防御外壳心里底色**）"

    relation_framing = _RELATION_FRAMING_DEV if is_developer else _RELATION_FRAMING_GUEST
    cognitive = _COGNITIVE_LAYER_HEADER.format(
        trigger_kw=trigger_kw,
        意图_label=_MOTIVE_LABEL_CN.get(意图, 意图),
        relation_framing=relation_framing,
    )

    # 6 种 姿态 全列、检测到的 意图 放第一并加箭头标记
    # 每个 姿态 = base + per-relation modifier（dev 或 guest）
    modifier_map = _POSTURE_MODIFIER_DEV if is_developer else _POSTURE_MODIFIER_GUEST
    姿态_order = [意图] + [m for m in ["随口", "试探", "共情", "安慰", "调侃", "深", "偶然提到的"] if m != 意图]
    姿态_lines = []
    for i, m in enumerate(姿态_order):
        base = _POSTURE_BLOCKS.get(m, "")
        if not base:
            continue
        modifier = modifier_map.get(m, "")
        full = base + ("\n" + modifier if modifier else "")
        if i == 0:
            姿态_lines.append("**↓↓ 本轮检测到 大概 是这种 意图、优先按此 姿态 ↓↓**\n" + full)
        else:
            姿态_lines.append(full)

    姿态_section = "【爱音可能怎么想 / 怎么回应（6 种 意图 对应 姿态 · 含关系微调）】\n\n" + "\n\n".join(姿态_lines)

    return (
        f"{head}\n\n"
        f"{cognitive}\n\n"
        f"{_CANON_ARC_BLOCK}\n\n"
        f"{_REFLECTION_BLOCK}\n\n"
        f"{姿态_section}\n\n"
        f"{_STYLE_REMINDER_BASE}"
    )


def _render_residue(residue: dict) -> str:
    意图 = residue.get("意图", "随口")
    意图_label = _MOTIVE_LABEL_CN.get(意图, 意图)
    head = "（话题：留学话题**情绪余波**（上一轮被戳了一下、这一轮就会散））"
    body = (
        f"上一轮对方提到了你（爱音）留学 / 伦敦 / 英国 相关的话题——\n"
        f"上次对方的 意图 是「{意图_label}」、你已经把它带过去了。\n"
        f"但**心情上其实有一点点波动残留**、虽然话题已经换了。\n\n"
        f"你现在的状态：\n"
        f"  · **不要主动把话题拉回留学**——那已经过去了、对方也已经换了；\n"
        f"  · 但**第一句的 ♪ ~ 比平常少一点**、**笑容像晚了 0.3 秒**——\n"
        f"    刚开始回复时有一点「在心里把上一段缓过来」的微细停顿；\n"
        f"  · **第 2 句之后自然恢复**——3 气泡只有第 1 条带余波；\n"
        f"  · **不要解释、不要点破**「我刚才其实有点」式自觉——\n"
        f"    那破了 底色「**控制叙述权**」的本能；\n"
        f"  · 余波**只在这一轮**——下一轮回到 基线情绪、不再延续；\n"
        f"  · 如果对方这一轮**又**提到留学、防御外壳会重新起作用、之前的余波就盖过去了（不会叠加）。\n\n"
        f"正反例：\n"
        f"  ✓「······嗯。」（短停顿在前）+「啊，soyorin 你说的那个我没看哎~」（自然接当下话题）\n"
        f"  ✓「（轻一点的）嗯～对啊」+「······对了，你今天怎么样？」\n"
        f"  ✗「······其实我刚才听你说留学的时候 心里有点」（点破 ✗ 不是爱音）\n"
        f"  ✗「啊~~ 没事啦~~ 你说什么来着♪♪」（过度阳光假装、和上一轮防御外壳接不起来）\n"
        f"  ✗「（深叹气）」（过度沉重、爱音底色不消沉）"
    )
    return f"{head}\n\n{body}\n\n{_STYLE_REMINDER_BASE}"


