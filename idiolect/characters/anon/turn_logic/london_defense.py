def build_london_defense_special_block(
    user_text: str,
    *,
    session_id: Optional[str] = None,
    is_developer: bool = False,
) -> str:
    """主入口：留学防御外壳 + 意图 自动分类 + 1 轮余波 + dev/guest 关系分流。

    **关系分流（用户拍板 2026-05-10）**：
      系统主 prompt 已注入「对方是青空（朋友）」 or「对方是访客（陌生人）」——
      爱音知道。本模块在两种关系下走不同的关系基调 + 姿态 微调：
        · is_developer=True：朋友基调、可放松一些、深 仍要慎、可漏一点温度
        · is_developer=False：陌生人基调、防御更紧、深 绝不打开、不漏温度

    **infra 行为**（撤销之前的 dev-skip）：
      residue 是真实心理状态、不按身份隔离——
      被青空老友戳到留下余波、被陌生人戳到也留下余波。
      session_id 已天然隔离会话（dev / guest 在 WS 层就是不同 session）、
      residue 不需要再按 is_developer 分。
      → **dev 和 guest 都正常 write / consume residue**。

    流程：
      1. 检测当前 turn 是否有 触发点 keyword
      2. 如有 触发点：
         - 判断是否爱音-linked
         - 分类 意图
         - 不爱音-linked（偶然提到的）：消化前 residue（如有）、不 起作用 防御外壳
         - 爱音-linked：渲染 full defense（按 is_developer 选关系基调和 姿态 微调）+ 写 residue
      3. 如无 触发点：检查 residue、有则渲染并 pop（一轮即清）

    Args:
        user_text:    本轮输入
        session_id:   ws 会话 id；None → fallback 单一 bucket
        is_developer: True = 对方是青空（你的老朋友）；False = 对方是刚认识的人陌生人。
                      影响 prompt 内的关系基调 + 6 个 姿态 的具体行为微调。
    """
    if not _enabled() or not user_text:
        return ""

    sid = _normalize_session(session_id)

    trigger_kw = _detect_trigger(user_text)
    if trigger_kw:
        anon_linked = _is_anon_linked(user_text, trigger_kw)
        意图 = _classify_意图(user_text, anon_linked)

        if 意图 == "偶然提到的":
            # 偶然提到的 不 起作用 防御、消化前 residue（如有）
            residue = _consume_residue(sid)
            if residue:
                return _render_residue(residue)
            return ""

        # 真正触发：full 起作用（按 is_developer 选关系基调和 姿态 微调）+ 写 residue
        out = _render_full_defense(user_text, trigger_kw, 意图, is_developer=is_developer)
        _set_residue(sid, 意图, user_text)
        return out

    # 无 触发点：消化前 residue（如有）
    residue = _consume_residue(sid)
    if residue:
        return _render_residue(residue)
    return ""


