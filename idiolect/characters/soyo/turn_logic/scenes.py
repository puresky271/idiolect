        #   A = 指向过去/前情或显式矛盾（昨天/上次/你自己说/不是…说/怎么又…）
        #   B = 表述/态度动词（说/讲/问/答应/提/要）
        # 试过 `(昨天)[^。！？]{0,10}(说)` 这类跨度模式，实测对「你昨天才说不想去」漏判
